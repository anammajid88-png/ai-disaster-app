const ADVANCE = 0.8;
const SPACE_ADVANCE = 0.46;

/** Width of `text` when drawn at the given cap height, in pixels. */
export function measureText(text, size, tracking = 0) {
  let width = 0;

  for (const character of text.toUpperCase()) {
    width += (character === ' ' ? SPACE_ADVANCE : ADVANCE) * size + tracking;
  }

  return Math.max(0, width - tracking);
}

/**
 * Converts `text` into polylines positioned at (x, y), where y is the cap top.
 * Unknown characters are skipped rather than drawn as a placeholder box.
 */
export function textPolylines(text, x, y, size, tracking = 0) {
  const polylines = [];
  let cursor = x;

  for (const character of text.toUpperCase()) {
    if (character === ' ') {
      cursor += SPACE_ADVANCE * size + tracking;
      continue;
    }

    const glyph = GLYPHS[character];

    if (glyph) {
      for (const line of glyph) {
        polylines.push(line.map(([gx, gy]) => [cursor + gx * size, y + gy * size]));
      }
    }

    cursor += ADVANCE * size + tracking;
  }

  return polylines;
}
